"""Secret key handling shared by session tokens and encrypted settings.

AUTH_SECRET_KEY stays in the environment (generated by the installer). It signs
session JWTs and, through HKDF, derives the key that encrypts secret values in
`app_settings`. Changing it logs everyone out AND makes stored secrets
unreadable: they must then be re-entered in the settings.
"""

from __future__ import annotations

import base64
import os

from cryptography.fernet import Fernet, InvalidToken
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

INSECURE_DEFAULT_SECRET_KEY = "change-me-in-production-use-a-long-random-string"
MIN_SECRET_KEY_LENGTH = 32
_SETTINGS_KDF_SALT = b"pbo-app-settings-v1"
_SETTINGS_KDF_INFO = b"app_settings encryption"
ENCRYPTED_PREFIX = "fernet:"


def get_secret_key() -> str:
    return os.getenv("AUTH_SECRET_KEY", INSECURE_DEFAULT_SECRET_KEY)


def validate_secret_key(secret_key: str | None = None) -> None:
    key = get_secret_key() if secret_key is None else secret_key
    if key == INSECURE_DEFAULT_SECRET_KEY:
        raise RuntimeError(
            "AUTH_SECRET_KEY was left at its insecure default. Anyone who reads the source code "
            "could forge a session. Generate one with: openssl rand -hex 32"
        )
    if len(key) < MIN_SECRET_KEY_LENGTH:
        raise RuntimeError(
            f"AUTH_SECRET_KEY is too short (must be at least {MIN_SECRET_KEY_LENGTH} characters). "
            "Generate one with: openssl rand -hex 32"
        )


def _settings_fernet(secret_key: str | None = None) -> Fernet:
    key_material = (get_secret_key() if secret_key is None else secret_key).encode("utf-8")
    derived = HKDF(
        algorithm=hashes.SHA256(),
        length=32,
        salt=_SETTINGS_KDF_SALT,
        info=_SETTINGS_KDF_INFO,
    ).derive(key_material)
    return Fernet(base64.urlsafe_b64encode(derived))


def encrypt_value(plaintext: str, secret_key: str | None = None) -> str:
    token = _settings_fernet(secret_key).encrypt(plaintext.encode("utf-8")).decode("ascii")
    return ENCRYPTED_PREFIX + token


class SecretDecryptionError(RuntimeError):
    pass


def decrypt_value(stored: str, secret_key: str | None = None) -> str:
    if not stored.startswith(ENCRYPTED_PREFIX):
        raise SecretDecryptionError("Stored secret is not in the expected encrypted format.")
    try:
        return _settings_fernet(secret_key).decrypt(stored[len(ENCRYPTED_PREFIX):].encode("ascii")).decode("utf-8")
    except InvalidToken as exc:
        raise SecretDecryptionError(
            "Stored secret cannot be decrypted (AUTH_SECRET_KEY changed?). Re-enter it in the settings."
        ) from exc
